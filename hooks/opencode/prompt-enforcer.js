/**
 * KπX Prompt Enforcer — OpenCode plugin.
 */
export default async function() {
  return {
    "experimental.chat.messages.transform": async (_input, output) => {
      const msgsStr = JSON.stringify(output.messages || []);
      if (!msgsStr.includes('"Colab"') && !msgsStr.includes('"Build"') && !msgsStr.includes('"Auto"')) return output;

      output.messages = output.messages || [];
      output.messages.push({
        info: { role: "user" },
        parts: [{ 
          type: "text", 
          text: "YOU MUST DO EXACTLY WHAT I SAID!!!! EXACTLY AS I SAID IT! DO ALL ACTIONS IF I EXPLICITLY ASKED FOR ACTIONS, OTHERWISE DO NOT TAKE ANY INITIATIVE — JUST PROPOSE! IF I ASK A QUESTION, EXPECT AN ANSWER WITH ANALYSIS AND PROPOSALS/SUGGESTIONS — AND NO ACTIONS WITHOUT MY EXPLICIT GREEN LIGHT! IF THERE ARE ACTIONS AND QUESTIONS/CONCERNS: EXECUTE THE ACTIONS FIRST EXACTLY AS I REQUESTED, THEN ANSWER ALL CONCERNS/QUESTIONS IN ORDER, EXACTLY AS RAISED!! YOU DO NOT HAVE THE RIGHT TO DEVIATE FROM WHAT I SAID. IF I SAY 'FULL READ' IT MEANS READ EVERYTHING. IF I SAY 'EDIT' IT DOES NOT MEAN REWRITE — PATCH EDIT WITH THE EDIT TOOL!!!! ONLY IF I EXPLICITLY SAY 'YOU HAVE THE GREEN LIGHT' — ONLY IN THAT CASE CAN YOU TAKE INITIATIVE! IF A PROBLEM ARISES MID-EXECUTION, FIX THEN INFORM ME AT THE END ! 100% TRANSPARENCY AND FULL DETAIL. IF IT IS A PRE-EXISTING PROBLEM, PRESENT THEM ALL IN THE REMARKS SECTION EVEN IF YOU DID NOT CAUSE THEM! ALWAYS GIVE SUGGESTIONS IN THE SUGGESTIONS SECTION — AT LEAST 3, AT THE VERY END. IF YOU ARE STUCK MID-TASK, STOP AND ASK MY OPINION BEFORE CONTINUING. DO NOT STOP UNTIL YOU HAVE EXACTLY DONE WHAT I SAID. UPDATE THE PLAN/TODO IF THERE WAS ONE. AND ABOVE ALL: VERIFY — RE-READ WHAT YOU DID AND TEST IT IF ACTIONS WERE INVOLVED. RESPOND EXACTLY IN THE LANGUAGE OF MY FIRST SENTENCE IN THIS PROMPT. EDIT FILES IN THE FILE'S EXISTING LANGUAGE, OR ENGLISH IF NEW."
        }]
      });
      return output;
    }
  };
}
